// Inlines the latin subsets of Inter + Plus Jakarta Sans (self-hosted,
// arch/13 section 4) into the login page, so the middleware can show the
// branded login without serving any file before the password is entered.
import { readFileSync, writeFileSync } from 'node:fs';

const files = {
  inter: 'node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2',
  jakarta: 'node_modules/@fontsource-variable/plus-jakarta-sans/files/plus-jakarta-sans-latin-wght-normal.woff2',
};
const b64 = Object.fromEntries(Object.entries(files).map(([k, p]) => [k, readFileSync(p).toString('base64')]));
writeFileSync('middleware-lib/fonts.ts',
  `// Generated by scripts/gen-login-fonts.mjs - do not edit.\n` +
  `export const INTER_WOFF2 = '${b64.inter}';\n` +
  `export const JAKARTA_WOFF2 = '${b64.jakarta}';\n`);
console.log('middleware-lib/fonts.ts written', Object.fromEntries(Object.entries(b64).map(([k, v]) => [k, `${Math.round(v.length / 1024)} KB`])));
