// Inlines the latin subsets of Inter + Plus Jakarta Sans (self-hosted,
// arch/13 section 4) into middleware.js, so the login page can be branded
// without serving any file before the password is entered.
import { readFileSync, writeFileSync } from 'node:fs';

const files = {
  INTER_WOFF2: 'node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2',
  JAKARTA_WOFF2: 'node_modules/@fontsource-variable/plus-jakarta-sans/files/plus-jakarta-sans-latin-wght-normal.woff2',
};
const start = '// ---- fonts (generated by scripts/gen-login-fonts.mjs, do not edit) ----';
const end = '// ---- end fonts ----';
const block = Object.entries(files).map(([k, p]) => `const ${k} = '${readFileSync(p).toString('base64')}';`).join('\n');

const src = readFileSync('middleware.js', 'utf8');
const a = src.indexOf(start), b = src.indexOf(end);
if (a < 0 || b < 0) throw new Error('font markers not found in middleware.js');
writeFileSync('middleware.js', src.slice(0, a + start.length) + '\n' + block + '\n' + src.slice(b));
console.log('fonts written into middleware.js');
